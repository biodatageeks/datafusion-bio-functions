"""Regenerate the data tables the kernels embed, from Biopython.

    python scripts/gen_tables.py           # rewrite the generated files
    python scripts/gen_tables.py --check   # exit 1 if a file is out of date

Needs Biopython and rustfmt on PATH. The checked-in files were made with
Biopython 1.88:

    uv run --no-project --with biopython==1.88 python scripts/gen_tables.py

Outputs (under src/kernels/):
  codon_tables.rs   amino acids, start codons and stop codons of every NCBI
                    translation table
  weights_data.rs   average and monoisotopic residue weights for DNA, RNA
                    and protein
"""

import subprocess
import sys
import tempfile
from pathlib import Path

import Bio
from Bio.Data import CodonTable, IUPACData

KERNELS = Path(__file__).resolve().parent.parent / "src" / "kernels"
BASES = "TCAG"  # NCBI codon order
CODONS = [a + b + c for a in BASES for b in BASES for c in BASES]


def codon_set(codons):
    """A bit set over the 64 codon indices."""
    mask = 0
    for codon in codons:
        mask |= 1 << CODONS.index(codon)
    return mask


def codon_tables():
    out = [
        f"// Generated by scripts/gen_tables.py from Biopython {Bio.__version__}",
        "// `Bio.Data.CodonTable.unambiguous_dna_by_id`. Do not edit by hand.",
        "//",
        "// `aa` lists the amino acid for every codon in NCBI order: the first, second",
        "// and third bases each run over T, C, A, G. Stops are `*`. Tables 27, 28 and",
        "// 31 list some codons as both a stop and an amino acid; like Biopython and",
        "// seqkit, `aa` holds the amino acid for them.",
        "//",
        "// `starts` and `stops` are bit sets over the same 64 codon indices (bit `i`",
        "// is codon `i`). `stops` includes the dual-meaning codons, so it can have",
        "// bits where `aa` is not `*`.",
        "",
        "/// One NCBI translation table.",
        "#[derive(Debug)]",
        "pub(crate) struct CodonTable {",
        "    pub id: u8,",
        "    pub aa: &'static [u8; 64],",
        "    pub starts: u64,",
        "    pub stops: u64,",
        "}",
        "",
        "pub(crate) static NCBI_TABLES: &[CodonTable] = &[",
    ]
    for table_id in sorted(CodonTable.unambiguous_dna_by_id):
        table = CodonTable.unambiguous_dna_by_id[table_id]
        aa = "".join(table.forward_table.get(codon, "*") for codon in CODONS)
        assert len(aa) == 64
        out += [
            f"    // {table.names[0]}",
            "    CodonTable {",
            f"        id: {table_id},",
            f'        aa: b"{aa}",',
            f"        starts: 0x{codon_set(table.start_codons):016x},",
            f"        stops: 0x{codon_set(table.stop_codons):016x},",
            "    },",
        ]
    out.append("];")
    return "\n".join(out) + "\n"


def weight_table(name, doc, table):
    rows = ", ".join(f"(b'{letter}', {table[letter]!r})" for letter in sorted(table))
    return [f"/// {doc}", f"pub(crate) static {name}: &[(u8, f64)] = &[{rows}];", ""]


def weights():
    out = [
        f"// Generated by scripts/gen_tables.py from Biopython {Bio.__version__}",
        "// `Bio.Data.IUPACData`. Do not edit by hand.",
        "//",
        "// The water masses are the constants in `Bio.SeqUtils.molecular_weight`.",
        "",
        "/// Average mass of water.",
        "pub(crate) const WATER: f64 = 18.0153;",
        "/// Monoisotopic mass of water.",
        "pub(crate) const WATER_MONOISOTOPIC: f64 = 18.010565;",
        "",
    ]
    data = IUPACData
    out += weight_table(
        "DNA_WEIGHTS", "`unambiguous_dna_weights`", data.unambiguous_dna_weights
    )
    out += weight_table(
        "DNA_WEIGHTS_MONOISOTOPIC",
        "`monoisotopic_unambiguous_dna_weights`",
        data.monoisotopic_unambiguous_dna_weights,
    )
    out += weight_table(
        "RNA_WEIGHTS", "`unambiguous_rna_weights`", data.unambiguous_rna_weights
    )
    out += weight_table(
        "RNA_WEIGHTS_MONOISOTOPIC",
        "`monoisotopic_unambiguous_rna_weights`",
        data.monoisotopic_unambiguous_rna_weights,
    )
    out += weight_table("PROTEIN_WEIGHTS", "`protein_weights`", data.protein_weights)
    out += weight_table(
        "PROTEIN_WEIGHTS_MONOISOTOPIC",
        "`monoisotopic_protein_weights`",
        data.monoisotopic_protein_weights,
    )
    return "\n".join(out).rstrip("\n") + "\n"


def rustfmt(text):
    with tempfile.NamedTemporaryFile("w", suffix=".rs", delete=False) as fh:
        fh.write(text)
    path = Path(fh.name)
    try:
        subprocess.run(["rustfmt", "--edition", "2024", str(path)], check=True)
        return path.read_text()
    finally:
        path.unlink()


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in [
        ("codon_tables.rs", codon_tables()),
        ("weights_data.rs", weights()),
    ]:
        text = rustfmt(text)
        path = KERNELS / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote {path}")
    if stale:
        sys.exit(f"out of date: {', '.join(stale)}; run scripts/gen_tables.py")


if __name__ == "__main__":
    main()
